#!/usr/bin/env python3
"""Download the Marmousi model and generate the Marmousi examples' data.

The examples under "Using the Marmousi model" in :doc:`examples` (starting
with :doc:`example_forward_model`) load two files from the current working
directory: ``marmousi_vp.bin`` (the Marmousi 1 P-wave velocity model, a
``751 * 2301`` grid of little-endian ``float32`` values at 4 m spacing, no
header, row-major with the 751-length depth axis outermost -- exactly
:func:`torch.from_file`'s ``size=751*2301`` followed by
``.reshape(751, 2301)``) and ``marmousi_data.bin`` (synthetic receiver data
generated by running :doc:`example_forward_model` at full size against that
model). This script produces both, in this directory (or ``--out-dir``):

1. Downloads the original Marmousi 1 Vp model from its canonical home, the
   Geoazur WIND project (``geoazur.fr/WIND``), verifying it against a
   recorded SHA-256 checksum, and writes it out as ``marmousi_vp.bin``. The
   Geoazur file is stored with the 2301-length horizontal axis outermost,
   so this step transposes it into the depth-first layout above, which is
   the convention the documentation uses throughout (dimension 0 is depth;
   see :ref:`axis-convention`). The transpose is done as an explicit
   parse/validate/re-encode round trip rather than a bare copy, so a change
   in the upstream format is caught here instead of silently propagating.

   The on-disk layout changed in Deepwave 0.1.0: it was previously the
   untransposed ``2301 * 751``. Since both layouts hold the same number of
   floats, a stale file would reshape without error, so this script and
   every example that loads ``marmousi_vp.bin`` check that row 0 really is
   the 1500 m/s water layer and raise if it is not.
2. Runs Deepwave's ``scalar`` propagator over that model with the same
   survey geometry as :doc:`example_forward_model`'s full-size run, and
   writes the resulting receiver data out as ``marmousi_data.bin``.

Redistribution note: this script downloads from the *original* Geoazur
source, not from a Deepwave-controlled host. Deepwave does not host or
redistribute a copy of the Marmousi model itself -- the Institut Francais
du Petrole (IFP), which created it, has not published redistribution terms
for it (unlike its elastic descendant, Marmousi2/AGL Elastic Marmousi,
which SEG's open-data initiative confirmed is CC BY 4.0; that is a
different, larger dataset with a different grid and does not cover the
original model this script downloads). If IFP/Geoazur redistribution
permission is obtained later, ``MIRROR_VP_URL`` below is where a
Deepwave-hosted mirror would be wired in.

Usage::

    python docs/get_marmousi.py            # full size (~126 MB data file)
    python docs/get_marmousi.py --smoke    # small crop, for quick testing
    python docs/get_marmousi.py --out-dir some/dir

Run it from wherever you intend to run the Marmousi examples from -- e.g.
``docs/`` if that's your working directory when running example scripts --
since that is where they look for ``marmousi_vp.bin``/``marmousi_data.bin``.

Those examples do not read the two files directly: they call
:func:`load_vp` and :func:`load_data` below. That keeps the file layout,
the staleness check and the error message in one place, and it gives them
their ``DEEPWAVE_SMOKE=1`` behaviour -- in that mode :func:`load_vp`
returns a generated stand-in model of the same shape and velocity range
(:func:`stand_in_vp`) and :func:`load_data` generates matching data, so
every example can be run as a quick check with no download at all.
"""

from __future__ import annotations

import argparse
import hashlib
import math
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import numpy as np
import numpy.typing as npt
import torch

import deepwave
from deepwave import scalar

# Canonical source: the Geoazur WIND project's own Marmousi page,
# https://www.geoazur.fr/WIND/bin/view/Main/Data/Marmousi (n1=751, n2=2301,
# d1=d2=4 m -- matching the grid every Marmousi example in this repository
# expects). The address below is the one that page links to. The server
# answers it with a small HTML page whose script forwards a browser to the
# file's current location, and that location has changed several times, so
# ``download_vp`` follows the forwarding page instead of relying on a fixed
# final address. Whatever arrives is accepted only if it matches the
# checksum below (taken 2026-08-10; the same bytes were served on
# 2026-09-21).
CANONICAL_VP_URL = (
    "https://www.geoazur.fr/WIND/pub/nfs/FWI-DATA/GEOMODELS/Marmousi/vp.bin"
)
CANONICAL_VP_SHA256 = (
    "f4302792e84bb7ddbdc9d4d0f963b9df32d9f648960084884127e186119b99dd"
)

# Optional Deepwave-hosted mirror of the same bytes. Left unset: hosting a
# copy requires IFP/Geoazur's explicit redistribution permission, which has
# not been sought or granted (see the module docstring). Until then this
# script always downloads from CANONICAL_VP_URL above.
# TODO(maintainer): if/when that permission is obtained, set both of these
# to a Deepwave-hosted copy (e.g. a GitHub Releases asset on ar4/deepwave)
# and its SHA-256; this script will then prefer the mirror automatically.
MIRROR_VP_URL: str | None = None
MIRROR_VP_SHA256: str | None = None

CITATION = (
    "Bourgeois, A., M. Bourget, P. Lailly, M. Poulet, P. Ricarte, and R. "
    "Versteeg, 1991, Marmousi, model and data: presented at the 1990 EAEG "
    "workshop on Practical Aspects of Seismic Data Inversion, EAEG."
)

# Grid of the model as this script writes it: depth first. Deepwave orders
# spatial dimensions slowest-varying first and names component suffixes from
# the fastest axis, so in 2-D the vertical (dimension 0) axis is the "y" one
# -- hence NY_FULL for the 751-sample depth extent and NX_FULL for the
# 2301-sample horizontal extent. The Geoazur download has these the other
# way round (see UPSTREAM_SHAPE); convert_vp transposes it.
NY_FULL = 751
NX_FULL = 2301
UPSTREAM_SHAPE = (NX_FULL, NY_FULL)
DX = 4.0

# Row 0 of the depth-first model is the Marmousi water layer, a constant
# 1500 m/s. An old-layout (untransposed) file has the same number of floats,
# so it reshapes without error; its row 0 crosses the whole depth range and
# reaches 5500 m/s. This threshold sits well clear of both.
WATER_LAYER_MAX_VP = 1600.0

N_SHOTS_FULL = 115
N_SOURCES_PER_SHOT = 1
D_SOURCE = 20
FIRST_SOURCE = 10
SOURCE_DEPTH = 2

N_RECEIVERS_PER_SHOT_FULL = 384
D_RECEIVER = 6
FIRST_RECEIVER = 0
RECEIVER_DEPTH = 2

FREQ = 25.0
NT_FULL = 750
DT = 0.004
PEAK_TIME = 1.5 / FREQ
ACCURACY = 8

# Reduced size for --smoke: mirrors example_forward_model.py's own
# DEEPWAVE_SMOKE=1 sizes, but as a real spatial crop of the downloaded model
# (rather than a raw reinterpretation of its first bytes), so the smoke run
# still propagates through physically sensible velocities.
SMOKE_NY = 150
SMOKE_NX = 300
SMOKE_N_SHOTS = 4
SMOKE_N_RECEIVERS_PER_SHOT = 40
SMOKE_NT = 200


def _sha256(path: Path) -> str:
    """Returns the SHA-256 hex digest of the file at ``path``."""
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _forwarded_url(downloaded: Path, url: str) -> str | None:
    """Returns where a forwarding page points, or ``None`` for a real file.

    The upstream server answers the published address with a page of a few
    hundred bytes containing ``location.href='/a'+'/b'+'/c/'+s`` (``s``
    is the file name). The model itself is several megabytes, so anything
    that small is read as such a page and the quoted path pieces are joined
    onto the same host. The checksum in :func:`download_vp` still decides
    whether the result is accepted.
    """
    if downloaded.stat().st_size > 4096:
        return None
    text = downloaded.read_text(errors="replace")
    match = re.search(
        r"location\.href\s*=\s*((?:'[^']*'\s*\+\s*)+)s\b", text
    )
    if match is None:
        return None
    path = "".join(re.findall(r"'([^']*)'", match.group(1)))
    parts = urllib.parse.urlsplit(url)
    if not path.startswith("/"):
        return None
    return f"{parts.scheme}://{parts.netloc}{path}{Path(parts.path).name}"


def download_vp(dest: Path) -> None:
    """Downloads the Marmousi Vp model to ``dest``, verifying its checksum.

    Prefers ``MIRROR_VP_URL`` when set, otherwise uses ``CANONICAL_VP_URL``.
    Raises ``RuntimeError`` (and removes the partial download) if the
    checksum does not match.
    """
    url = MIRROR_VP_URL or CANONICAL_VP_URL
    expected_sha256 = (
        MIRROR_VP_SHA256 if MIRROR_VP_URL else CANONICAL_VP_SHA256
    )
    if (
        expected_sha256 is None
    ):  # pragma: no cover - both-or-neither by construction
        raise RuntimeError(
            "MIRROR_VP_URL is set but MIRROR_VP_SHA256 is not."
        )
    print(f"Downloading Marmousi Vp model from {url} ...")
    tmp = dest.with_suffix(dest.suffix + ".part")
    urllib.request.urlretrieve(url, tmp)  # noqa: S310 - fixed https URL above, checksummed below
    forwarded = _forwarded_url(tmp, url)
    if forwarded is not None:
        print(f"... forwarded to {forwarded}")
        urllib.request.urlretrieve(forwarded, tmp)  # noqa: S310 - same https host, checksummed below
    actual_sha256 = _sha256(tmp)
    if actual_sha256 != expected_sha256:
        tmp.unlink(missing_ok=True)
        raise RuntimeError(
            f"Checksum mismatch for {url}: expected {expected_sha256}, got "
            f"{actual_sha256}. The download has been removed; if this "
            "recurs, the source may have changed -- do not proceed "
            "without re-verifying the new checksum against a trusted copy. "
            "The file has moved on the upstream server before, and what "
            "arrives then is a small HTML page rather than a model, which "
            "is exactly what "
            "this check catches: look for the current location of vp.bin "
            "from https://www.geoazur.fr/WIND/bin/view/Main/Data/Marmousi, "
            "and once you have verified it is the same model, point this "
            "script at it by setting MIRROR_VP_URL and MIRROR_VP_SHA256 at "
            "the top of this file."
        )
    tmp.replace(dest)
    print(f"Verified SHA-256 {actual_sha256} -- wrote {dest}")


def check_depth_first(
    vp: npt.NDArray[np.float32] | torch.Tensor, source: Path
) -> None:
    """Raises if ``vp`` is not in the depth-first layout.

    Row 0 of the depth-first Marmousi model is the constant 1500 m/s water
    layer. The pre-0.1.0 layout has the same number of floats, so it
    reshapes without error; this catches that instead of silently
    propagating a rotated model.
    """
    row0_max = float(vp[0].max())
    if row0_max > WATER_LAYER_MAX_VP:
        raise RuntimeError(
            f"{source} looks transposed: row 0 reaches {row0_max:g} m/s, "
            "but the depth-first layout's row 0 is the 1500 m/s water "
            "layer. marmousi_vp.bin's layout changed in Deepwave 0.1.0; "
            "delete the old file and re-run `python docs/get_marmousi.py`."
        )


def convert_vp(src: Path, dest: Path) -> npt.NDArray[np.float32]:
    """Reads the downloaded Vp file and re-writes it in Deepwave's format.

    The Geoazur file is little-endian float32 with no header, laid out with
    the 2301-length horizontal axis outermost (``UPSTREAM_SHAPE``).
    Deepwave's documentation puts depth in dimension 0, so this transposes
    it to ``(NY_FULL, NX_FULL)`` before writing. The conversion is explicit
    (parse, validate shape/dtype, transpose, re-encode) rather than a bare
    file copy, so a future change in the upstream format would be caught
    here instead of silently propagating. Returns the array (used by
    :func:`generate_data` to avoid re-reading the file it just wrote).
    """
    raw = np.fromfile(src, dtype="<f4")
    if raw.size != NY_FULL * NX_FULL:
        raise RuntimeError(
            f"{src} has {raw.size} float32 values, expected "
            f"{NY_FULL * NX_FULL} ({NY_FULL} * {NX_FULL}). The upstream "
            "file format may have changed; do not proceed without "
            "re-deriving the expected grid size."
        )
    upstream = raw.reshape(UPSTREAM_SHAPE)
    vp = np.ascontiguousarray(upstream.T).astype("<f4", copy=False)
    check_depth_first(vp, src)
    vp.tofile(dest)
    print(
        f"Wrote {dest} ({vp.shape[0]} x {vp.shape[1]} float32, depth "
        f"first, "
        f"{DX} m spacing; transposed from the {UPSTREAM_SHAPE[0]} x "
        f"{UPSTREAM_SHAPE[1]} upstream layout)"
    )
    return vp


def survey(
    n_shots: int,
    n_receivers_per_shot: int,
    nt: int,
    *,
    device: torch.device | None = None,
    cells_per_4m: int = 1,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Builds the canonical Marmousi survey used by every example here.

    Returns ``(source_amplitudes, source_locations, receiver_locations)``
    for the first ``n_shots`` shots and ``n_receivers_per_shot`` receivers
    of the survey described in :doc:`example_forward_model`, recorded for
    ``nt`` time steps. ``cells_per_4m`` rescales the grid indices for a
    model sampled more coarsely than the 4 m original (``2`` for the 8 m
    grid :doc:`example_rtm` migrates on); the physical positions are the
    same either way.
    """
    if cells_per_4m < 1:
        raise ValueError("cells_per_4m must be at least 1")
    source_locations = torch.zeros(
        n_shots, N_SOURCES_PER_SHOT, 2, dtype=torch.long, device=device
    )
    source_locations[..., 0] = SOURCE_DEPTH // cells_per_4m
    source_locations[:, 0, 1] = (
        torch.arange(n_shots) * D_SOURCE + FIRST_SOURCE
    ) // cells_per_4m

    receiver_locations = torch.zeros(
        n_shots, n_receivers_per_shot, 2, dtype=torch.long, device=device
    )
    receiver_locations[..., 0] = RECEIVER_DEPTH // cells_per_4m
    receiver_locations[:, :, 1] = (
        (torch.arange(n_receivers_per_shot) * D_RECEIVER + FIRST_RECEIVER)
        // cells_per_4m
    ).repeat(n_shots, 1)

    source_amplitudes = (
        deepwave.wavelets.ricker(FREQ, nt, DT, PEAK_TIME)
        .repeat(n_shots, N_SOURCES_PER_SHOT, 1)
        .to(device)
    )
    return source_amplitudes, source_locations, receiver_locations


def stand_in_vp(ny: int = NY_FULL, nx: int = NX_FULL) -> torch.Tensor:
    """Builds a generated velocity model with Marmousi's shape and scale.

    This is *not* Marmousi: it is a water layer over gently folded layers
    whose velocity increases with depth, on the same ``751 x 2301`` grid at
    the same 4 m spacing and over the same 1500-5500 m/s range. The
    examples use it in place of the downloaded model when
    ``DEEPWAVE_SMOKE=1`` is set, so that they can be run as a quick check
    without a network download. Every structure in the resulting figures is
    an artefact of this stand-in, so use the real model (see
    :func:`download_vp`) for anything you intend to interpret.
    """
    depth = torch.arange(ny, dtype=torch.float32).reshape(ny, 1)
    horizontal = torch.arange(nx, dtype=torch.float32).reshape(1, nx)
    # Fold the layer boundaries into a gentle anticline, so that the model
    # is not purely one-dimensional and reflections have some dip.
    fold = 10.0 * torch.cos(2 * math.pi * horizontal / max(nx, 1))
    layer = torch.floor((depth + fold).clamp(min=0.0) / 20.0)
    vp = (1500.0 + 100.0 * layer).clamp(1500.0, 5500.0)
    # A water layer of the same thickness as Marmousi's, ~96 m.
    vp[: max(round(ny * 24 / NY_FULL), 1)] = 1500.0
    return vp


def load_vp(
    *, smoke: bool = False, source_dir: Path | None = None
) -> torch.Tensor:
    """Returns the ``751 x 2301`` Marmousi Vp model as a float32 tensor.

    With ``smoke=True`` it returns :func:`stand_in_vp` instead, so that an
    example can be run as a quick check without the download. Otherwise it
    reads ``marmousi_vp.bin`` from ``source_dir`` (default: the current
    working directory), checking that it is in the depth-first layout this
    script writes.
    """
    if smoke:
        return stand_in_vp()
    path = (source_dir or Path.cwd()) / "marmousi_vp.bin"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Run `python docs/get_marmousi.py` from "
            f"{path.parent} to download the Marmousi model and generate "
            "the data file the examples read, or set DEEPWAVE_SMOKE=1 to "
            "run this example on a generated stand-in model instead."
        )
    vp = torch.from_file(
        str(path), size=NY_FULL * NX_FULL, dtype=torch.float32
    ).reshape(NY_FULL, NX_FULL)
    check_depth_first(vp, path)
    return vp


def load_data(
    v_true: torch.Tensor,
    n_shots: int,
    n_receivers_per_shot: int,
    nt: int,
    *,
    smoke: bool = False,
    source_dir: Path | None = None,
) -> torch.Tensor:
    """Returns observed data shaped ``[shot, receiver, time]``.

    Normally this is the first ``n_shots`` shots, ``n_receivers_per_shot``
    receivers and ``nt`` time samples of ``marmousi_data.bin``, the file
    :func:`generate_data` writes.

    With ``smoke=True`` there is no downloaded model to have generated that
    file from, so the data is instead produced here by propagating through
    ``v_true`` (the model the calling example is about to invert), with the
    same survey. That makes the smoke run an inverse crime -- the observed
    data comes from exactly the model being sought -- which is fine for
    checking that an example runs, and useless as a demonstration that the
    method works. The figures in the documentation all come from the real
    model and the real data file.
    """
    if smoke:
        source_amplitudes, source_locations, receiver_locations = survey(
            n_shots, n_receivers_per_shot, nt, device=v_true.device
        )
        return scalar(
            v_true.detach(),
            DX,
            DT,
            source_amplitudes=source_amplitudes,
            source_locations=source_locations,
            receiver_locations=receiver_locations,
            accuracy=ACCURACY,
            pml_freq=FREQ,
        ).receiver_amplitudes.detach()
    path = (source_dir or Path.cwd()) / "marmousi_data.bin"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Run `python docs/get_marmousi.py` from "
            f"{path.parent} to download the Marmousi model and generate "
            "this file, or set DEEPWAVE_SMOKE=1 to run this example on "
            "generated data instead."
        )
    return (
        torch.from_file(
            str(path),
            size=N_SHOTS_FULL * N_RECEIVERS_PER_SHOT_FULL * NT_FULL,
            dtype=torch.float32,
        )
        .reshape(N_SHOTS_FULL, N_RECEIVERS_PER_SHOT_FULL, NT_FULL)[
            :n_shots, :n_receivers_per_shot, :nt
        ]
        .clone()
    )


def generate_data(
    vp: npt.NDArray[np.float32], dest: Path, *, smoke: bool
) -> None:
    """Runs the ``scalar`` propagator and writes ``marmousi_data.bin``.

    Uses the same survey geometry as :doc:`example_forward_model`'s
    full-size run (or the reduced ``--smoke`` sizes over a spatial crop of
    ``vp``), so the result matches what every other Marmousi example in
    this repository expects to load.
    """
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if smoke:
        ny, nx = SMOKE_NY, SMOKE_NX
        n_shots = SMOKE_N_SHOTS
        n_receivers_per_shot = SMOKE_N_RECEIVERS_PER_SHOT
        nt = SMOKE_NT
    else:
        ny, nx = NY_FULL, NX_FULL
        n_shots = N_SHOTS_FULL
        n_receivers_per_shot = N_RECEIVERS_PER_SHOT_FULL
        nt = NT_FULL
    v = torch.from_numpy(vp[:ny, :nx].copy()).to(device)

    source_amplitudes, source_locations, receiver_locations = survey(
        n_shots, n_receivers_per_shot, nt, device=device
    )

    print(
        f"Propagating {n_shots} shots over a {ny} x {nx} grid "
        f"(depth x horizontal) for "
        f"{nt} steps ({'smoke' if smoke else 'full'} size) ..."
    )
    out = scalar(
        v,
        DX,
        DT,
        source_amplitudes=source_amplitudes,
        source_locations=source_locations,
        receiver_locations=receiver_locations,
        accuracy=ACCURACY,
        pml_freq=FREQ,
    )
    receiver_amplitudes = out.receiver_amplitudes
    if not torch.isfinite(receiver_amplitudes).all():
        raise RuntimeError("Generated receiver data is not finite.")
    if receiver_amplitudes.abs().max() == 0:
        raise RuntimeError("Generated receiver data is all zeros.")
    receiver_amplitudes.cpu().numpy().tofile(dest)
    print(f"Wrote {dest} ({tuple(receiver_amplitudes.shape)} float32)")


def main(argv: list[str] | None = None) -> int:
    """Parses arguments and runs the download/convert/generate pipeline."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path.cwd(),
        help="Directory to write the two output files to (default: cwd).",
    )
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="Generate a small data file quickly, to test this script.",
    )
    parser.add_argument(
        "--skip-download",
        action="store_true",
        help="Reuse an existing marmousi_vp.bin in --out-dir instead of "
        "downloading.",
    )
    args = parser.parse_args(argv)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    vp_dest = args.out_dir / "marmousi_vp.bin"
    data_dest = args.out_dir / "marmousi_data.bin"

    if args.skip_download and vp_dest.exists():
        print(f"Reusing existing {vp_dest}")
        vp = np.fromfile(vp_dest, dtype="<f4").reshape(NY_FULL, NX_FULL)
        check_depth_first(vp, vp_dest)
    else:
        raw_dest = args.out_dir / "marmousi_vp_raw_download.bin"
        download_vp(raw_dest)
        vp = convert_vp(raw_dest, vp_dest)
        raw_dest.unlink()

    generate_data(vp, data_dest, smoke=args.smoke)
    print(
        f"\nDone. {vp_dest} and {data_dest} are ready.\n"
        f"Citation: {CITATION}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
